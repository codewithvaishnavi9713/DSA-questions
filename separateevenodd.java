public class separateevenodd {
    public static void main(String[] args){
        int[] arr={1,4,5,2,6,8,7};

        int n= arr.length;
        for(int i=0;i<n;i++){
            if(arr[i]%2==0){
                System.out.print(arr[i]);
            }
            else{
                System.out.print(arr[i]);
            }
        }


    }
    
}
